export const UI_STRINGS: Record<Language, Record<UIStringKey, string>> = {
  en: EN,
  hi: HI,
  kn: KN,
  ta: TA,
  ml: ML,
  mr: MR,
  pa: PA,
  es: ES,
  zh: ZH,
};

/** Interpolates `{var}` placeholders in a template string. */
function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in vars ? String(vars[key]) : match));
}

/** Looks up `key` in `lang`'s table, falling back to English, then the raw key. */
export function translate(lang: Language, key: UIStringKey, vars?: Record<string, string | number>): string {
  const table = UI_STRINGS[lang] ?? UI_STRINGS.en;
  const template = table[key] ?? UI_STRINGS.en[key] ?? key;
  return interpolate(template, vars);
}
